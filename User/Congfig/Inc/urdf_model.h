/**
 * @file urdf_model.h
 * @brief URDF坐标系运动学模型参数
 * @version 0.3
 * @date 2025-01-XX
 *
 * 直接使用URDF文件的坐标变换，无MDH转换误差
 *
 * 参数来源: Manipulator_Right.urdf (左臂电机损坏，暂不支持)
 *
 * 坐标系: 与URDF完全一致，每个关节的坐标系由<origin>元素定义
 *
 * 特点:
 * - 100%精确，无任何近似或转换误差
 * - 惯性参数可在Ozone调试器中实时修改
 * - 质心位置直观（在关节坐标系下表达）
 * - 参数固定后可手动添加 const 修饰符
 *
 * @copyright ZLLC 2027
 */

#define URDF_JOINT_NUM  CONTROLLER_JOINT_NUM

/**
 * @brief URDF连杆数据结构
 */
struct Struct_URDF_Link
{
    float xyz[3];        // 关节位置 [m]
    float R[9];          // 旋转矩阵（行主序，预计算）
    float axis[3];       // 关节旋转轴
    float q_min;         // 下限 [rad]
    float q_max;         // 上限 [rad]

    // 惯性参数（可在Ozone中修改）
    float mass;          // 质量 [kg]
    float com[3];        // 质心位置 [m]（在关节坐标系下）
    float I[6];          // 惯性张量 {Ixx, Iyy, Izz, Ixy, Ixz, Iyz} [kg*m^2]
};

